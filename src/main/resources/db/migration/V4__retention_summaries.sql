-- =====================================================================================================
-- V4: retention (RR-12). With application.retention.events-days set, a daily job deletes check-in records,
-- calendar statuses, status requests and absence alerts older than that, after rolling the check-ins and
-- statuses up into one summary per person per month: days checked in, time in, and days per status.
-- Reports read the summaries for the months the details are gone from. Nothing here changes existing rows.
-- =====================================================================================================

CREATE TABLE attendance_summaries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dn              varchar(255) NOT NULL,
    -- The first day of the month summarised.
    month           date NOT NULL,
    days_checked_in integer NOT NULL DEFAULT 0,
    -- First check-in to last check-out, per day, as the reports count it.
    minutes_in      bigint NOT NULL DEFAULT 0,
    updated_at      timestamp(6) with time zone NOT NULL,
    CONSTRAINT attendance_summaries_month_check CHECK (extract(day FROM month) = 1)
);
-- One summary per person and month, ignoring DN case; also the lookup reports and the purge make.
CREATE UNIQUE INDEX ux_attendance_summaries_dn_month ON attendance_summaries (lower(dn), month);

CREATE TABLE attendance_summary_statuses (
    summary_id bigint NOT NULL REFERENCES attendance_summaries (id) ON DELETE CASCADE,
    status     varchar(50) NOT NULL,
    days       integer NOT NULL,
    PRIMARY KEY (summary_id, status),
    CONSTRAINT attendance_summary_statuses_status_check
        CHECK (status IN ('STANDARD', 'OUT_OF_OFFICE', 'WORK_FROM_HOME', 'TDY', 'SCHEDULED_LEAVE',
                          'UNSCHEDULED_LEAVE', 'ABSENT_EXCUSED', 'ABSENT_UNEXCUSED', 'ABSENT', 'EARLY_LEAVE',
                          'LATE_ARRIVAL'))
);

-- One row: what the purge has done. Each of its batches locks it, so purges on several instances take turns
-- rather than summarising the same records twice.
CREATE TABLE retention_state (
    id            integer PRIMARY KEY,
    -- Records before this day have been summarised and deleted; null until the first purge.
    purged_before date,
    last_run_at   timestamp(6) with time zone,
    CONSTRAINT retention_state_one_row CHECK (id = 1)
);
INSERT INTO retention_state (id) VALUES (1);

