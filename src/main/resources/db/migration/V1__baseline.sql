-- --- The audit trail is append-only ---------------------------------------------------------------------
-- UPDATE is refused for everyone, so a stored event can only be added, or deleted by retention pruning.
-- Tampering would also be caught by the hash chain (Verify integrity on the audit page); this stops the
-- casual case outright.
CREATE OR REPLACE FUNCTION audit_events_append_only() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit_events is append-only: stored audit events cannot be changed (seq %)', OLD.seq;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
                   WHERE tgrelid = 'audit_events'::regclass AND tgname = 'audit_events_no_update') THEN
        CREATE TRIGGER audit_events_no_update
            BEFORE UPDATE ON audit_events
            FOR EACH ROW EXECUTE FUNCTION audit_events_append_only();
    END IF;
END $$;

