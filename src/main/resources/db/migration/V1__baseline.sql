-- --- Constraints ---------------------------------------------------------------------------------------

-- A permission belongs to a user. Hibernate named this key with a hash (fk34rv7...); it is renamed, or
-- created when missing, so every database has the same name.
DO $$
DECLARE
    existing text;
BEGIN
    SELECT c.conname INTO existing
    FROM pg_constraint c
    WHERE c.conrelid = 'permission_records'::regclass AND c.contype = 'f'
      AND c.confrelid = 'user_records'::regclass
    LIMIT 1;
    IF existing IS NULL THEN
        ALTER TABLE permission_records ADD CONSTRAINT fk_permission_records_user
            FOREIGN KEY (user_id) REFERENCES user_records (id);
    ELSIF existing <> 'fk_permission_records_user' THEN
        EXECUTE format('ALTER TABLE permission_records RENAME CONSTRAINT %I TO fk_permission_records_user', existing);
    END IF;
END $$;

-- One event id per audit event, one hash per pull-API token. Hibernate created these as constraints;
-- db/legacy/002 as plain unique indexes on a table it found without them. Either is kept.
DO $$
BEGIN
    IF to_regclass('ux_audit_events_event_id') IS NULL THEN
        ALTER TABLE audit_events ADD CONSTRAINT ux_audit_events_event_id UNIQUE (event_id);
    END IF;
    IF to_regclass('ux_audit_api_tokens_hash') IS NULL THEN
        ALTER TABLE audit_api_tokens ADD CONSTRAINT ux_audit_api_tokens_hash UNIQUE (token_hash);
    END IF;
END $$;

-- The enumerated columns accept the values the application writes. Hibernate added these checks with the
-- values the enum had when it created the table, so an older database may have a shorter list (and so
-- refuse a newer status); they are replaced with the current lists. A change to one of these enums needs
-- a migration that replaces its check the same way. Existing rows are checked separately, below.
ALTER TABLE check_in_out_records DROP CONSTRAINT IF EXISTS check_in_out_records_action_check;
ALTER TABLE check_in_out_records ADD CONSTRAINT check_in_out_records_action_check
    CHECK (action IN ('CHECK_IN', 'CHECK_OUT', 'LOCK', 'UNLOCK')) NOT VALID;

ALTER TABLE user_records DROP CONSTRAINT IF EXISTS user_records_user_role_check;
ALTER TABLE user_records ADD CONSTRAINT user_records_user_role_check
    CHECK (user_role IN ('USER', 'MANAGER', 'ADMIN')) NOT VALID;

ALTER TABLE user_event_records DROP CONSTRAINT IF EXISTS user_event_records_status_check;
ALTER TABLE user_event_records ADD CONSTRAINT user_event_records_status_check
    CHECK (status IN ('STANDARD', 'OUT_OF_OFFICE', 'WORK_FROM_HOME', 'TDY', 'SCHEDULED_LEAVE',
                      'UNSCHEDULED_LEAVE', 'ABSENT_EXCUSED', 'ABSENT_UNEXCUSED', 'ABSENT', 'EARLY_LEAVE',
                      'LATE_ARRIVAL')) NOT VALID;

ALTER TABLE notification_records DROP CONSTRAINT IF EXISTS notification_records_type_check;
ALTER TABLE notification_records ADD CONSTRAINT notification_records_type_check
    CHECK (type IN ('ABSENT')) NOT VALID;

ALTER TABLE notification_records DROP CONSTRAINT IF EXISTS notification_records_status_response_check;
ALTER TABLE notification_records ADD CONSTRAINT notification_records_status_response_check
    CHECK (status_response IN ('STANDARD', 'OUT_OF_OFFICE', 'WORK_FROM_HOME', 'TDY', 'SCHEDULED_LEAVE',
                               'UNSCHEDULED_LEAVE', 'ABSENT_EXCUSED', 'ABSENT_UNEXCUSED', 'ABSENT',
                               'EARLY_LEAVE', 'LATE_ARRIVAL')) NOT VALID;

-- Existing rows: a value no longer in the enum leaves its check NOT VALID (still enforced for new rows)
-- rather than failing the upgrade. ReadyRoom could not read such a row anyway; the notice names it.
DO $$
DECLARE
    pending record;
BEGIN
    FOR pending IN
        SELECT conrelid::regclass AS tbl, conname
        FROM pg_constraint
        WHERE NOT convalidated AND contype = 'c'
          AND conname IN ('check_in_out_records_action_check', 'user_records_user_role_check',
                          'user_event_records_status_check', 'notification_records_type_check',
                          'notification_records_status_response_check')
    LOOP
        BEGIN
            EXECUTE format('ALTER TABLE %s VALIDATE CONSTRAINT %I', pending.tbl, pending.conname);
        EXCEPTION WHEN check_violation THEN
            RAISE WARNING 'Rows in % hold values % does not allow; left NOT VALID', pending.tbl, pending.conname;
        END;
    END LOOP;
END $$;

-- --- One user record per DN, ignoring case --------------------------------------------------------------
-- Concurrent first sign-ins of earlier releases could create two rows for one DN in different letter case.
-- Before the unique index below, any such rows are merged as db/legacy/001 did: the oldest row is kept, its
-- empty fields are filled from the duplicates, favourites and alternate managers are combined, the most
-- privileged role wins and permissions move across without repeating a group. A no-op on a database that
-- ran 001, or has no duplicates.
LOCK TABLE user_records IN SHARE ROW EXCLUSIVE MODE;

CREATE TEMP TABLE user_record_duplicates ON COMMIT DROP AS
SELECT id, keep_id
FROM (SELECT id, min(id) OVER (PARTITION BY lower(dn)) AS keep_id FROM user_records) ranked
WHERE id <> keep_id;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM user_record_duplicates) THEN
        RAISE WARNING 'Merging % duplicate user record(s) into % user(s)',
            (SELECT count(*) FROM user_record_duplicates),
            (SELECT count(DISTINCT keep_id) FROM user_record_duplicates);
    END IF;
END $$;

WITH grouped AS (
    SELECT g.keep_id,
           -- every row of the group, kept row included, oldest first
           array_agg(u.id ORDER BY u.id) AS ids
    FROM (SELECT DISTINCT keep_id FROM user_record_duplicates) g
    JOIN user_records u ON lower(u.dn) = (SELECT lower(dn) FROM user_records WHERE id = g.keep_id)
    GROUP BY g.keep_id
),
merged AS (
    SELECT g.keep_id,
           (array_agg(u.notes                 ORDER BY u.id) FILTER (WHERE u.notes                 IS NOT NULL))[1] AS notes,
           (array_agg(u.organization          ORDER BY u.id) FILTER (WHERE u.organization          IS NOT NULL))[1] AS organization,
           (array_agg(u.employee_type         ORDER BY u.id) FILTER (WHERE u.employee_type         IS NOT NULL))[1] AS employee_type,
           (array_agg(u.location              ORDER BY u.id) FILTER (WHERE u.location              IS NOT NULL))[1] AS location,
           (array_agg(u.branch                ORDER BY u.id) FILTER (WHERE u.branch                IS NOT NULL))[1] AS branch,
           (array_agg(u.duty_sub_organization ORDER BY u.id) FILTER (WHERE u.duty_sub_organization IS NOT NULL))[1] AS duty_sub_organization,
           (array_agg(u.phone_number          ORDER BY u.id) FILTER (WHERE u.phone_number          IS NOT NULL))[1] AS phone_number,
           (array_agg(u.email                 ORDER BY u.id) FILTER (WHERE u.email                 IS NOT NULL))[1] AS email,
           (array_agg(u.average_login_time    ORDER BY u.id) FILTER (WHERE u.average_login_time    IS NOT NULL))[1] AS average_login_time,
           (array_agg(u.chosen_login_time     ORDER BY u.id) FILTER (WHERE u.chosen_login_time     IS NOT NULL))[1] AS chosen_login_time,
           (array_agg(u.user_role ORDER BY CASE u.user_role WHEN 'ADMIN' THEN 1 WHEN 'MANAGER' THEN 2 WHEN 'USER' THEN 3 ELSE 4 END, u.id)
                FILTER (WHERE u.user_role IS NOT NULL))[1] AS user_role,
           nullif(array_to_string(ARRAY(
               SELECT DISTINCT v FROM user_records x, unnest(string_to_array(x.favorite_groups, ';')) AS v
               WHERE x.id = ANY (g.ids) AND v <> '' ORDER BY v), ';'), '') AS favorite_groups,
           nullif(array_to_string(ARRAY(
               SELECT DISTINCT v FROM user_records x, unnest(string_to_array(x.alternate_managers, ';')) AS v
               WHERE x.id = ANY (g.ids) AND v <> '' ORDER BY v), ';'), '') AS alternate_managers
    FROM grouped g
    JOIN user_records u ON u.id = ANY (g.ids)
    GROUP BY g.keep_id, g.ids
)
UPDATE user_records k
SET notes                 = m.notes,
    organization          = m.organization,
    employee_type         = m.employee_type,
    location              = m.location,
    branch                = m.branch,
    duty_sub_organization = m.duty_sub_organization,
    phone_number          = m.phone_number,
    email                 = m.email,
    average_login_time    = m.average_login_time,
    chosen_login_time     = m.chosen_login_time,
    user_role             = m.user_role,
    favorite_groups       = m.favorite_groups,
    alternate_managers    = m.alternate_managers
FROM merged m
WHERE k.id = m.keep_id;

-- Permissions: drop a duplicate's grant the kept user already holds, then move the rest across.
DELETE FROM permission_records p
USING user_record_duplicates d, permission_records kept
WHERE p.user_id = d.id
  AND kept.user_id = d.keep_id
  AND lower(kept.group_dn) = lower(p.group_dn);

UPDATE permission_records p
SET user_id = d.keep_id
FROM user_record_duplicates d
WHERE p.user_id = d.id;

-- Two duplicates may both have held the same grant; keep one.
DELETE FROM permission_records p
USING permission_records q
WHERE p.user_id = q.user_id
  AND lower(p.group_dn) = lower(q.group_dn)
  AND p.id > q.id
  AND p.user_id IN (SELECT keep_id FROM user_record_duplicates);

DELETE FROM user_records u
USING user_record_duplicates d
WHERE u.id = d.id;

-- --- Indexes ---------------------------------------------------------------------------------------------
-- An index an interrupted CREATE INDEX CONCURRENTLY (db/legacy/001 or 002) left INVALID would be skipped by
-- IF NOT EXISTS for ever; drop any such leftover of ours so it is built again.
DO $$
DECLARE
    leftover text;
BEGIN
    FOR leftover IN
        SELECT c.relname
        FROM pg_index i
        JOIN pg_class c ON c.oid = i.indexrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = current_schema()
          AND NOT i.indisvalid
          AND (c.relname LIKE 'ix\_%' OR c.relname LIKE 'ux\_%')
    LOOP
        RAISE WARNING 'Dropping invalid index % left by an earlier failed run', leftover;
        EXECUTE format('DROP INDEX %I', leftover);
    END LOOP;
END $$;

