-- =====================================================================================================
-- V1: the whole ReadyRoom schema as of the move to Flyway - every table, column, index, constraint and
-- trigger the application needs. Run by Flyway when ReadyRoom starts (see db/README.md).
--
-- Written to be safe on any database it can meet:
--   - an empty one (a new install): it creates everything;
--   - one an earlier ReadyRoom created with Hibernate's ddl-auto: update, with or without the hand-run
--     scripts db/legacy/001 and 002: it adds only what is missing. Tables, columns and indexes use
--     IF NOT EXISTS, and constraints and the trigger are created only when absent, so what is already
--     there is left as it is. Columns are added one by one so a database from any older release gets
--     the columns added since; on such a database they are added without NOT NULL, as Hibernate did.
--
-- Flyway runs it in one transaction, so it either applies completely or not at all. That rules out
-- CREATE INDEX CONCURRENTLY: indexes db/legacy/001 never built are built here while ReadyRoom is still
-- starting and serves nothing, which on a large check_in_out_records table takes a minute or so.
--
-- Do not edit this file once released: Flyway checks it has not changed. Add V2__..., V3__... instead.
-- =====================================================================================================

-- IF NOT EXISTS reports every column and index already there as a NOTICE, which Flyway would log as a
-- warning dozens of times on a fresh database. Only real warnings (the RAISE WARNINGs below) are passed on.
