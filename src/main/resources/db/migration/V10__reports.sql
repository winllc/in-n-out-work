-- =====================================================================================================
-- V10: time zones in reports, and scheduled reports (RR-19).
--
-- user_records.time_zone: the IANA time zone a person chose on their profile for their times in reports,
-- exports and the public API; null for their site's (application.reports.site-time-zones) or the
-- application's. Existing people get null: nothing they see changes.
--
-- report_schedules: group attendance reports e-mailed daily, weekly or monthly, to recipients (DNs) who
-- may run the report themselves; both checked again at every run.
-- =====================================================================================================

ALTER TABLE user_records ADD COLUMN time_zone varchar(64);

CREATE TABLE report_schedules (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200)  NOT NULL,
    owner_dn    varchar(1000) NOT NULL,
    group_dn    varchar(1000) NOT NULL,
    frequency   varchar(20)   NOT NULL,
    format      varchar(10)   NOT NULL,
    recipients  varchar(4000) NOT NULL,
    time_zone   varchar(64)   NOT NULL,
    send_hour   integer       NOT NULL,
    enabled     boolean       NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    last_run_at timestamp(6) with time zone,
    next_run_at timestamp(6) with time zone,
    last_result varchar(500),
    CONSTRAINT report_schedules_frequency_check CHECK (frequency IN ('DAILY', 'WEEKLY', 'MONTHLY')),
    CONSTRAINT report_schedules_format_check CHECK (format IN ('csv', 'xlsx')),
    CONSTRAINT report_schedules_hour_check CHECK (send_hour BETWEEN 0 AND 23)
);

CREATE INDEX ix_report_schedules_due ON report_schedules (enabled, next_run_at);
CREATE INDEX ix_report_schedules_owner_lower ON report_schedules (lower(owner_dn));
