-- =====================================================================================================
-- V6: several replicas (RR-10).
--
-- shedlock: one row per scheduled job that must run on one replica at a time (the directory sync, the
-- automatic check-out, absence alerts, the retention purges, session clean-up, audit forwarding). The job
-- that holds a row's lock runs; the others skip that run. The columns are ShedLock's own (JdbcTemplate
-- provider), written in database time.
--
-- spring_session, spring_session_attributes: browser sessions, so any replica can serve any request and a
-- restart or a rolling update no longer signs everyone out. Spring Session's PostgreSQL schema, except that
-- principal_name holds a whole directory DN (Spring's default is 100 characters).
--
-- service_heartbeat, service_outage: every running instance updates the heartbeat; a gap in it is an outage
-- of the whole service, during which the Windows client's events were lost. Absence alerts and automatic
-- check-outs then give people time to be seen again before acting on what is missing (cron.ServiceOutages).
-- The heartbeat starts now, so the first start of this release measures from the upgrade.
-- =====================================================================================================

CREATE TABLE shedlock (
    name       varchar(64)  NOT NULL PRIMARY KEY,
    lock_until timestamp(3) NOT NULL,
    locked_at  timestamp(3) NOT NULL,
    locked_by  varchar(255) NOT NULL
);

CREATE TABLE spring_session (
    primary_id            char(36)      NOT NULL,
    session_id            char(36)      NOT NULL,
    creation_time         bigint        NOT NULL,
    last_access_time      bigint        NOT NULL,
    max_inactive_interval int           NOT NULL,
    expiry_time           bigint        NOT NULL,
    principal_name        varchar(1024),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);
CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id char(36)     NOT NULL,
    attribute_name     varchar(200) NOT NULL,
    attribute_bytes    bytea        NOT NULL,
    CONSTRAINT spring_session_attributes_pk PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);

CREATE TABLE service_heartbeat (
    id       integer PRIMARY KEY,
    beat_at  timestamp(6) with time zone NOT NULL,
    instance varchar(255),
    CONSTRAINT service_heartbeat_one_row CHECK (id = 1)
);
INSERT INTO service_heartbeat (id, beat_at, instance) VALUES (1, now(), 'migration V6');

CREATE TABLE service_outage (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    down_from  timestamp(6) with time zone NOT NULL,
    down_until timestamp(6) with time zone NOT NULL
);
CREATE INDEX ix_service_outage_until ON service_outage (down_until);
