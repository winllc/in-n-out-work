-- =====================================================================================================
-- V2: status requests (RR-07). A status that excuses an absence (leave, telework, TDY, out of office,
-- absent excused; application.events.request-statuses) is no longer set by the person: they request it,
-- and it reaches the calendar (user_event_records) only once their manager, a delegate or an
-- administrator approves it. Each calendar day an approval writes points back at its request.
--
-- Existing statuses are left as they are: they were set before approval existed and keep their effect
-- (request_id stays null, as for every status set or recorded directly).
-- =====================================================================================================

CREATE TABLE status_requests (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_dn    varchar(255) NOT NULL,
    status          varchar(50)  NOT NULL,
    from_date       date NOT NULL,
    to_date         date NOT NULL,
    login_by_time   time(0) without time zone,
    note            varchar(500),
    state           varchar(20)  NOT NULL,
    created_at      timestamp(6) with time zone NOT NULL,
    decided_by_dn   varchar(255),
    decided_at      timestamp(6) with time zone,
    decision_note   varchar(500),
    cancelled_by_dn varchar(255),
    cancelled_at    timestamp(6) with time zone,
    CONSTRAINT status_requests_state_check
        CHECK (state IN ('REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT status_requests_status_check
        CHECK (status IN ('STANDARD', 'OUT_OF_OFFICE', 'WORK_FROM_HOME', 'TDY', 'SCHEDULED_LEAVE',
                          'UNSCHEDULED_LEAVE', 'ABSENT_EXCUSED', 'ABSENT_UNEXCUSED', 'ABSENT', 'EARLY_LEAVE',
                          'LATE_ARRIVAL')),
    CONSTRAINT status_requests_dates_check CHECK (to_date >= from_date)
);

-- A person's own requests, and the approval queue (pending requests of the people an approver decides for).
CREATE INDEX ix_status_requests_requester_lower ON status_requests (lower(requester_dn), state);
CREATE INDEX ix_status_requests_state ON status_requests (state, from_date);
-- Retention: requests whose last day is past the cutoff.
CREATE INDEX ix_status_requests_to_date ON status_requests (to_date);

-- The approved request a calendar day comes from. Cancelling the request removes its days; a day the person
-- later sets themselves loses the link.
ALTER TABLE user_event_records ADD COLUMN request_id bigint;
ALTER TABLE user_event_records ADD CONSTRAINT fk_user_event_records_request
    FOREIGN KEY (request_id) REFERENCES status_requests (id) ON DELETE SET NULL;
CREATE INDEX ix_user_events_request_id ON user_event_records (request_id);
