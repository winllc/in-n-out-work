-- =====================================================================================================
-- V9: the public API and signed webhooks (RR-14).
--
-- api_tokens: tokens for /api/v1, created by administrators. Only each token's SHA-256 is stored, with its
-- first characters for display, its scopes (space separated), the administrator it acts for (owner_dn), an
-- expiry and a rate limit. Revoked tokens are kept, marked, for the record.
--
-- webhook_endpoints: HTTPS endpoints that receive signed events. The signing secret is stored encrypted
-- (AES-256-GCM under application.webhooks.secret-key), never in clear.
--
-- webhook_deliveries: the queue of events to send, one row per event and endpoint, and the delivery log
-- (attempts, last status and error). Finished rows are deleted after application.webhooks.delivery-log-days.
-- claimed_until: the replica sending a row holds it until then, so no row is sent twice at once.
--
-- New tables only: nothing existing changes.
-- =====================================================================================================

CREATE TABLE api_tokens (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  varchar(200)  NOT NULL,
    token_hash            varchar(64)   NOT NULL,
    token_prefix          varchar(16)   NOT NULL,
    scopes                varchar(200)  NOT NULL,
    owner_dn              varchar(1000) NOT NULL,
    created_at            timestamp(6) with time zone NOT NULL,
    expires_at            timestamp(6) with time zone NOT NULL,
    rate_limit_per_minute integer       NOT NULL,
    last_used_at          timestamp(6) with time zone,
    revoked_at            timestamp(6) with time zone,
    revoked_by            varchar(1000),
    CONSTRAINT ux_api_tokens_hash UNIQUE (token_hash),
    CONSTRAINT api_tokens_rate_check CHECK (rate_limit_per_minute > 0)
);

CREATE TABLE webhook_endpoints (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(200)  NOT NULL,
    url               varchar(2000) NOT NULL,
    events            varchar(200)  NOT NULL,
    secret_ciphertext varchar(400)  NOT NULL,
    secret_prefix     varchar(16)   NOT NULL,
    owner_dn          varchar(1000) NOT NULL,
    created_at        timestamp(6) with time zone NOT NULL,
    disabled_at       timestamp(6) with time zone,
    disabled_by       varchar(1000),
    last_success_at   timestamp(6) with time zone,
    last_failure_at   timestamp(6) with time zone,
    last_error        varchar(500),
    silent_failures   integer       NOT NULL DEFAULT 0,
    paused_until      timestamp(6) with time zone
);

CREATE TABLE webhook_deliveries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id     bigint       NOT NULL,
    event_id        varchar(36)  NOT NULL,
    event_type      varchar(50)  NOT NULL,
    payload         text         NOT NULL,
    state           varchar(20)  NOT NULL,
    attempts        integer      NOT NULL,
    next_attempt_at timestamp(6) with time zone,
    last_attempt_at timestamp(6) with time zone,
    last_status     integer,
    last_error      varchar(500),
    created_at      timestamp(6) with time zone NOT NULL,
    delivered_at    timestamp(6) with time zone,
    claimed_until   timestamp(6) with time zone,
    CONSTRAINT webhook_deliveries_state_check CHECK (state IN ('PENDING', 'DELIVERED', 'FAILED')),
    CONSTRAINT fk_webhook_deliveries_endpoint FOREIGN KEY (endpoint_id)
        REFERENCES webhook_endpoints (id) ON DELETE CASCADE
);

CREATE INDEX ix_webhook_deliveries_due ON webhook_deliveries (state, next_attempt_at);
CREATE INDEX ix_webhook_deliveries_endpoint ON webhook_deliveries (endpoint_id, created_at);
